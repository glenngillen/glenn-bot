"""
Data models for the browsable library.

This module defines:
- ContentType: Enum of all supported content types
- LibraryItem: Unified data structure for all knowledge base items
- Theme: AI-generated thematic category
- ThemeAssignment: Item-to-theme mapping with confidence score
"""

from dataclasses import dataclass
from datetime import datetime
from enum import Enum
from typing import Any, Optional


class ContentType(Enum):
    """Enum of supported content types for library items."""

    BOOK = "book"
    ARTICLE = "article"
    FRAMEWORK = "framework"
    VALUE = "value"
    PREFERENCE = "preference"
    MEMORY = "memory"
    INSIGHT = "insight"
    GOAL = "goal"
    SKILL = "skill"
    WEB_CONTENT = "web_content"


@dataclass
class LibraryItem:
    """Unified data structure for all knowledge base items.

    Represents a single item in the browsable library, supporting
    all content types with sufficient metadata for display, grouping,
    and search.
    """

    id: str
    content_type: ContentType
    title: str
    summary: str
    full_content: str
    source_url: Optional[str]
    cover_image_url: Optional[str]
    metadata: dict[str, Any]
    themes: list[str]
    created_at: datetime
    highlights: list[str]

    def to_dict(self) -> dict[str, Any]:
        """Convert the LibraryItem to a dictionary for serialization.

        Returns:
            A dictionary with all fields serialized. ContentType is converted
            to its string value, and datetime is converted to ISO format.
        """
        return {
            "id": self.id,
            "content_type": self.content_type.value,
            "title": self.title,
            "summary": self.summary,
            "full_content": self.full_content,
            "source_url": self.source_url,
            "cover_image_url": self.cover_image_url,
            "metadata": self.metadata,
            "themes": self.themes,
            "created_at": self.created_at.isoformat(),
            "highlights": self.highlights,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "LibraryItem":
        """Create a LibraryItem from a dictionary.

        Args:
            data: A dictionary with LibraryItem fields. The content_type
                should be a string value, and created_at should be an
                ISO format datetime string.

        Returns:
            A new LibraryItem instance.
        """
        return cls(
            id=data["id"],
            content_type=ContentType(data["content_type"]),
            title=data["title"],
            summary=data["summary"],
            full_content=data["full_content"],
            source_url=data["source_url"],
            cover_image_url=data["cover_image_url"],
            metadata=data["metadata"],
            themes=data["themes"],
            created_at=datetime.fromisoformat(data["created_at"]),
            highlights=data["highlights"],
        )


@dataclass
class Theme:
    """AI-generated thematic category for grouping library items.

    Themes are broad categories that group related content across all
    content types. They are generated by AI analysis of the knowledge
    base and can be updated incrementally as new content is added.
    """

    id: str  # Unique identifier (slug format, e.g., "systems-thinking")
    name: str  # Display name
    description: str  # Brief description of the theme
    keywords: list[str]  # Representative keywords for the theme
    item_count: int  # Number of items in this theme
    created_at: datetime  # When the theme was created
    updated_at: datetime  # When the theme was last updated

    def to_dict(self) -> dict[str, Any]:
        """Convert the Theme to a dictionary for serialization.

        Returns:
            A dictionary with all fields serialized. Datetime fields
            are converted to ISO format strings.
        """
        return {
            "id": self.id,
            "name": self.name,
            "description": self.description,
            "keywords": self.keywords,
            "item_count": self.item_count,
            "created_at": self.created_at.isoformat(),
            "updated_at": self.updated_at.isoformat(),
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "Theme":
        """Create a Theme from a dictionary.

        Args:
            data: A dictionary with Theme fields. The created_at and
                updated_at fields should be ISO format datetime strings.

        Returns:
            A new Theme instance.
        """
        return cls(
            id=data["id"],
            name=data["name"],
            description=data["description"],
            keywords=data["keywords"],
            item_count=data["item_count"],
            created_at=datetime.fromisoformat(data["created_at"]),
            updated_at=datetime.fromisoformat(data["updated_at"]),
        )


@dataclass
class ThemeAssignment:
    """Mapping between a library item and a theme with confidence score.

    ThemeAssignments represent the many-to-many relationship between
    LibraryItems and Themes. Each assignment includes a confidence score
    indicating how strongly the item belongs to the theme.
    """

    item_id: str  # ID of the library item
    theme_id: str  # ID of the theme
    confidence: float  # Confidence score from 0.0 to 1.0
    assigned_at: datetime  # When the assignment was made

    def to_dict(self) -> dict[str, Any]:
        """Convert the ThemeAssignment to a dictionary for serialization.

        Returns:
            A dictionary with all fields serialized. The assigned_at
            datetime is converted to ISO format string.
        """
        return {
            "item_id": self.item_id,
            "theme_id": self.theme_id,
            "confidence": self.confidence,
            "assigned_at": self.assigned_at.isoformat(),
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "ThemeAssignment":
        """Create a ThemeAssignment from a dictionary.

        Args:
            data: A dictionary with ThemeAssignment fields. The assigned_at
                field should be an ISO format datetime string.

        Returns:
            A new ThemeAssignment instance.
        """
        return cls(
            item_id=data["item_id"],
            theme_id=data["theme_id"],
            confidence=data["confidence"],
            assigned_at=datetime.fromisoformat(data["assigned_at"]),
        )
